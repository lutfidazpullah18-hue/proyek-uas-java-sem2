    private void tjmlKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_tjmlKeyPressed
if(evt.getKeyCode() == java.awt.event.KeyEvent.VK_ENTER) {
        
        // 1. Ambil data dari kolom jumlah
        int jumlah = Integer.parseInt(tjml.getText());
        
        // 2. Masukkan ke class Obat (untuk diproses rumusnya)
        brg.setJml(jumlah);
        
        // 3. Tampilkan hasil perhitungan ke kolom Total
        ttot.setText(Double.toString(brg.getTot()));
        
        // 4. Pindahkan kursor ke kolom Uang Bayar agar user tidak perlu pakai mouse
        tubyr.grabFocus();
    }        // TODO add your handling code here:
    }//GEN-LAST:event_tjmlKeyPressed

