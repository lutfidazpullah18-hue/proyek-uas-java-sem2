    private void cbkodeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cbkodeActionPerformed
String kode = (String) cbkode.getSelectedItem();
    
    // 2. Berikan kode ke class Obat untuk mencari data
    brg.setKd(kode);
    
    // 3. Ambil Nama & Harga hasil pencarian, lalu tampilkan
    nb.setText(brg.getNb());
    thrg.setText(Double.toString(brg.getHrg()));
    
    // 4. Setelah harga muncul, pindahkan kursor ke Jumlah agar user bisa langsung ketik
    tjml.requestFocus();        // TODO add your handling code here:
    }//GEN-LAST:event_cbkodeActionPerformed

